"""Build _data/papers.json, papers.json and papers.bib from arXiv metadata + curation.py."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from curation import TOPICS, PAPERS
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
raw = json.load(open(os.path.join(ROOT, "tools", "arxiv_metadata.json")))
topics = []
for key, name, blurb in TOPICS:
    items = []
    for pid, (t, summ) in PAPERS.items():
        if t != key: continue
        m = raw[pid]
        items.append(dict(id=pid, title=m["title"], authors=m["authors"], year=int(m["published"][:4]),
                          published=m["published"], abs_url=f"https://arxiv.org/abs/{pid}",
                          pdf_url=f"https://arxiv.org/pdf/{pid}", doi=m.get("doi"), journal_ref=m.get("journal_ref"),
                          summary=summ))
    items.sort(key=lambda x: (-x["year"], x["title"]))
    topics.append(dict(key=key, name=name, blurb=blurb, papers=items))
data = dict(source="arXiv API (export.arxiv.org); metadata verbatim, summaries hand-written from abstracts",
            count=sum(len(t["papers"]) for t in topics), topics=topics)
for path in ("_data/papers.json", "papers.json", "assets/data/papers.json"):
    json.dump(data, open(os.path.join(ROOT, path), "w"), indent=2, ensure_ascii=False)

def bibkey(p):
    last = re.sub(r"[^A-Za-z]", "", p["authors"][0].split()[-1]) or "anon"
    word = re.sub(r"[^A-Za-z]", "", p["title"].split()[0]).lower()
    return f"{last.lower()}{p['year']}{word}"
def esc(s): return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")
out = ["% GIS in Motion reading list -- generated by tools/build_data.py from the arXiv API", ""]
for t in topics:
    out.append(f"% ---- {t['name']} ----")
    for p in t["papers"]:
        fields = [f"  title         = {{{{{esc(p['title'])}}}}}",
                  f"  author        = {{{' and '.join(p['authors'])}}}",
                  f"  year          = {{{p['year']}}}",
                  f"  eprint        = {{{p['id']}}}",
                  f"  archivePrefix = {{arXiv}}",
                  f"  url           = {{{p['abs_url']}}}",
                  f"  keywords      = {{{t['key']}}}"]
        if p["doi"]: fields.append(f"  doi           = {{{p['doi']}}}")
        if p["journal_ref"]: fields.append(f"  note          = {{{esc(p['journal_ref'])}}}")
        out.append(f"@misc{{{bibkey(p)},\n" + ",\n".join(fields) + "\n}\n")
open(os.path.join(ROOT, "papers.bib"), "w").write("\n".join(out))
print("papers:", data["count"], {t["key"]: len(t["papers"]) for t in topics})
